#!/usr/bin/env node
// Generates the Renderer's Lucide icon module from the reviewed local assets in
// resources/icons/lucide (see resources/icons/README.md and manifest.json for the
// pinned upstream commit and hashes). Run after adding or upgrading an icon:
//
//   node scripts/generate-lucide-icons.mjs
//
// Only inner markup is copied, verbatim modulo collapsed whitespace, so the
// rendered icon keeps the upstream geometry, stroke width and currentColor.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'resources', 'icons', 'lucide');
const target = join(root, 'apps', 'desktop', 'renderer', 'src', 'tool-icon-paths.tsx');

// Names are the local SVG file names; the mapping to Tool identity lives in
// tool-icon.tsx so this file stays a pure asset view.
const names = [
  'activity',
  'check',
  'chevron-down',
  'chevron-right',
  'chevrons-down-up',
  'circle-alert',
  'circle-question-mark',
  'circle-slash',
  'copy',
  'corner-down-right',
  'external-link',
  'file-code',
  'file-diff',
  'file-pen-line',
  'file-search',
  'file-text',
  'folder-open',
  'folder-tree',
  'git-branch',
  'globe',
  'link',
  'list-checks',
  'list-end',
  'loader-circle',
  'minimize-2',
  'octagon-x',
  'package-minus',
  'package-plus',
  'package-search',
  'panel-right-open',
  'pause',
  'pencil',
  'play',
  'shield-alert',
  'sparkles',
  'square',
  'target',
  'terminal',
  'trash',
  'undo-2',
  'wrench',
];

// One top-level element per line: Prettier then keeps the reviewed geometry as
// is instead of reflowing one long run of inline siblings into `{' '}` breaks.
const splitTopLevel = (body) => {
  const parts = [];
  let start = 0;
  let depth = 0;
  let index = 0;
  while (index < body.length) {
    const open = body.indexOf('<', index);
    if (open === -1) break;
    const close = body.indexOf('>', open);
    if (close === -1) throw new Error(`unterminated element in ${body}`);
    const tag = body.slice(open, close + 1);
    if (depth === 0 && open > start) parts.push(body.slice(start, open).trim());
    if (tag.startsWith('</')) depth -= 1;
    else if (!tag.endsWith('/>')) depth += 1;
    if (depth === 0) {
      parts.push(body.slice(start, close + 1).trim());
      start = close + 1;
    }
    index = close + 1;
  }
  const tail = body.slice(start).trim();
  if (tail !== '') parts.push(tail);
  if (depth !== 0) throw new Error(`unbalanced icon markup: ${body}`);
  return parts.filter((part) => part !== '');
};

const inner = (name) => {
  const svg = readFileSync(join(source, `${name}.svg`), 'utf8');
  const match = svg.match(/>([\s\S]*)<\/svg>/u);
  if (match === null) throw new Error(`no SVG body in ${name}.svg`);
  const body = match[1].replaceAll(/\s+/gu, ' ').trim();
  if (body === '' || /<script|on\w+=|<!ENTITY|<!DOCTYPE/iu.test(body)) {
    throw new Error(`unexpected content in ${name}.svg`);
  }
  return splitTopLevel(body).join('\n      ');
};

// Prettier's `quoteProps: as-needed` default drops quotes a plain identifier does
// not need; emitting that here keeps the generated module format-clean as is.
const key = (name) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/u.test(name) ? name : `'${name}'`);

const entries = names
  .map((name) => `  ${key(name)}: (\n    <>\n      ${inner(name)}\n    </>\n  ),`)
  .join('\n');

const content = `// Generated by scripts/generate-lucide-icons.mjs from resources/icons/lucide.
// Do not edit by hand: change the reviewed asset and regenerate instead.
import type { ReactNode } from 'react';

export type LucideIconName =
${names.map((name) => `  | '${name}'`).join('\n')};

export const LUCIDE_ICON_PATHS: Record<LucideIconName, ReactNode> = {
${entries}
};
`;

writeFileSync(target, content, 'utf8');
console.log(`generated ${target.slice(root.length + 1)} (${names.length} icons)`);
