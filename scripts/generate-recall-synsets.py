"""Build the local synonym table from the pinned Chinese Open Wordnet archive."""

import argparse
from collections import Counter, defaultdict
from hashlib import sha256
from pathlib import Path
from tarfile import open as open_archive
from xml.etree import ElementTree


ARCHIVE_SHA256 = "93e9357dda50a38ce626904c2229479afa177df74d9c504aebfeba06ff2f241e"
ROOT = Path(__file__).resolve().parent.parent


def extract(source: Path) -> tuple[list[tuple[str, ...]], str]:
    if sha256(source.read_bytes()).hexdigest() != ARCHIVE_SHA256:
        raise ValueError("Expected the official Chinese Open Wordnet 1.1 archive")
    with open_archive(source, "r:xz") as archive:
        with archive.extractfile("cow/cow-1.1.xml") as wordnet:
            root = ElementTree.parse(wordnet).getroot()
        with archive.extractfile("cow/LICENSE") as license_file:
            license_text = license_file.read().decode("utf-8").strip()
    groups = defaultdict(set)
    for entry in root.findall("./Lexicon/LexicalEntry"):
        term = entry.find("Lemma").attrib["writtenForm"]
        if not 2 <= len(term) <= 8 or not all("\u3400" <= c <= "\u9fff" for c in term):
            continue
        for sense in entry.findall("Sense"):
            groups[sense.attrib["synset"]].add(term)
    relevant = [group for group in groups.values() if 2 <= len(group) <= 8]
    frequency = Counter(term for group in relevant for term in group)
    unambiguous = {tuple(sorted(term for term in group if frequency[term] <= 4)) for group in relevant}
    return sorted(group for group in unambiguous if len(group) > 1), license_text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path)
    args = parser.parse_args()
    groups, license_text = extract(args.archive)
    license_path = ROOT / "resources/third-party-notices/chinese-open-wordnet-1.1-LICENSE.txt"
    license_path.write_text(license_text + "\n", encoding="utf-8", newline="\n")
    data = ROOT / "crates/aura-persistence-v2/src/retrieval/generated/chinese-synsets.tsv"
    data.parent.mkdir(parents=True, exist_ok=True)
    header = "# Generated by scripts/generate-recall-synsets.py from Chinese Open Wordnet 1.1\n"
    notice = "\n".join(f"# {line.rstrip()}".rstrip() for line in license_text.splitlines())
    table = "\n".join("\t".join(group) for group in groups)
    data.write_text(f"{header}{notice}\n{table}\n", encoding="utf-8", newline="\n")
    print(f"{len(groups)} synonym sets, {data.stat().st_size} bytes")


if __name__ == "__main__":
    main()
