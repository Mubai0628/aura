export async function expectSecureSurface(page: Page): Promise<void> {
  const capabilities = await page.evaluate(() => {
    const rendererGlobal = globalThis as typeof globalThis & { aura: { v1: AuraApiV1 } };
    return {
      apiKeys: Object.keys(rendererGlobal.aura.v1).sort(),
      mainErrorApiKeys: Object.keys(rendererGlobal.aura.v1.mainErrors ?? {}).sort(),
      memoryApiKeys: Object.keys(rendererGlobal.aura.v1.memory ?? {}).sort(),
      electron: typeof Reflect.get(rendererGlobal, 'electron'),
      nodeProcess: typeof Reflect.get(rendererGlobal, 'process'),
      nodeRequire: typeof Reflect.get(rendererGlobal, 'require'),
    };
  });
  expect(capabilities).toEqual({
    apiKeys: rendererApiKeys,
    mainErrorApiKeys: ['onChange', 'snapshot'],
    memoryApiKeys: ['invoke'],
    electron: 'undefined',
    nodeProcess: 'undefined',
    nodeRequire: 'undefined',
  });
}
